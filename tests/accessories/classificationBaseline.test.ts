import { CommandClasses } from '@zwave-js/core';
import { AccessoryFactory } from '../../src/accessories/AccessoryFactory';
import { IZWaveNode } from '../../src/zwave/interfaces';
import { createHash } from 'crypto';
import baseline from '../fixtures/classificationBaseline.json';
import { CLASSIFICATION_SHAPES, SHAPE_CC } from '../fixtures/classificationShapes';

/**
 * sha256 over every shape's `[supported, values, endpoints, kinds, signature, category]`, in
 * shape order, taken from the classifier as it stood at `245d984`. The 37 named cases below
 * read well when one breaks; this covers the other 1,885, which a representative set cannot:
 * a regression could misclassify a shape that no longer has its own case and still produce
 * only outcomes the old classifier produced.
 */
const BASELINE_SHAPE_COUNT = 1922;
const BASELINE_HASH = '4f2260992100906113da5dd0ddd74d563c088781e64cc161504876f83c3755d2';

/**
 * What every supported device published before item 13 touched the classifier.
 *
 * The fixture was generated by running these node shapes through the classifier as it stood at
 * `245d984`, the commit before the planner existed, and recording the kinds, the graph signature
 * and the accessory category for each. Item 13 splits that classifier apart and teaches it to
 * accept an override; it must not change what any device publishes when nobody has asked for
 * one, because a changed signature rebuilds a live accessory and a changed category rewrites
 * its cache. Every entry here is one outcome the old classifier produced.
 */
describe('classification is unchanged without an override', () => {
  const nodeFor = (entry: (typeof baseline)[number]): IZWaveNode => {
    const codes = new Set(
      entry.supported.map(
        (name) => (CommandClasses as unknown as Record<string, number>)[name],
      ),
    );
    const endpoints = entry.endpoints.map((index) => ({
      index,
      supportsCC: (code: number) => codes.has(code),
    }));

    return {
      nodeId: 7,
      ready: true,
      getAllEndpoints: () => endpoints,
      getDefinedValueIDs: () => entry.values,
      getValueMetadata: () => undefined,
      getValue: () => undefined,
    } as unknown as IZWaveNode;
  };

  it('covers every distinct outcome the old classifier produced', () => {
    expect(baseline.length).toBeGreaterThan(30);
  });

  it('maps every one of the shapes to exactly what it mapped to before', () => {
    const nodeForShape = (shape: (typeof CLASSIFICATION_SHAPES)[number]) => {
      const codes = new Set(shape.supported.map((name) => SHAPE_CC[name]));
      const endpoints = (shape.endpoints ?? [0]).map((index) => ({
        index,
        supportsCC: (code: number) => codes.has(code),
      }));

      return {
        nodeId: 7,
        ready: true,
        getAllEndpoints: () => endpoints,
        getDefinedValueIDs: () => shape.values,
        getValueMetadata: () => undefined,
        getValue: () => undefined,
      } as unknown as IZWaveNode;
    };

    expect(CLASSIFICATION_SHAPES).toHaveLength(BASELINE_SHAPE_COUNT);

    const canonical = CLASSIFICATION_SHAPES.map((shape) => {
      const node = nodeForShape(shape);
      const plans = AccessoryFactory.planFeatures(node);

      return JSON.stringify([
        shape.supported,
        shape.values,
        shape.endpoints ?? [0],
        plans.map((plan) => plan.effectiveKinds),
        AccessoryFactory.signatureOfPlans(plans),
        (AccessoryFactory as unknown as { getCategory(p: unknown): number }).getCategory(plans),
      ]);
    }).join('\n');

    expect(createHash('sha256').update(canonical).digest('hex')).toBe(BASELINE_HASH);
  });

  baseline.forEach((entry, index) => {
    const label = entry.supported.length ? entry.supported.join(' + ') : 'no command classes';
    const detail = entry.values.length
      ? ` with ${entry.values.map((v) => v.property).join(', ')}`
      : '';

    it(`publishes the same services for ${label}${detail} (#${index})`, () => {
      const node = nodeFor(entry);
      const plans = AccessoryFactory.planFeatures(node);

      expect(plans.map((plan) => plan.effectiveKinds)).toEqual(entry.kinds);
      expect(AccessoryFactory.signatureOfPlans(AccessoryFactory.planFeatures(node))).toBe(entry.signature);
      expect(
        (AccessoryFactory as unknown as { getCategory(p: unknown): number }).getCategory(plans),
      ).toBe(entry.category);
    });
  });
});
